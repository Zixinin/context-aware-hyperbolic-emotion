"""Check runtime logging instrumentation leaves the original scientific loop intact."""
import ast
from pathlib import Path
import sys
import types
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from launch import instrument_train
from protocol import source_audit


class LauncherTests(unittest.TestCase):
    def test_frozen_original_loop_only_gains_one_logging_statement(self):
        source = (ROOT.parents[1] / 'experiments/exp2_lgsa/code/goemotions_adaptation/run.py').read_text()
        tree = ast.parse(source)
        original = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'train')
        # Build an unexecuted function so inspect.getsource can use the real file.
        namespace = {}
        exec(compile(ast.Module(body=[original], type_ignores=[]),
             str(ROOT.parents[1] / 'experiments/exp2_lgsa/code/goemotions_adaptation/run.py'), 'exec'), namespace)
        legacy = types.SimpleNamespace(train=namespace['train'])
        observed = []
        # Intercept compilation to inspect the actual AST generated by the launcher.
        import launch
        builtin_compile = compile
        def capture(tree, filename, mode):
            observed.append(tree)
            return builtin_compile(tree, filename, mode)
        launch.compile = capture
        try:
            instrument_train(legacy, lambda entry: {})
        finally:
            del launch.compile
        self.assertEqual(len(observed), 1)
        generated = observed[0]
        class Remove(ast.NodeTransformer):
            count = 0
            def visit_Expr(self, node):
                if 'exp3_step_diagnostics' in ast.unparse(node):
                    self.count += 1
                    return None
                return node
        removal = Remove()
        cleaned = removal.visit(generated)
        self.assertEqual(removal.count, 1)
        self.assertEqual(ast.dump(cleaned.body[0], include_attributes=False), ast.dump(original, include_attributes=False))


if __name__ == '__main__':
    unittest.main()
